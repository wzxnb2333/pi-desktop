test('regeneration with a changed reference leaves the branch draft and shows its send failure', async () => {
  const detail = contextDetailSchema.parse(await fixture.invoke({ op: 'composer.contextDetail', threadId: 't', reference: { kind: 'file', id: 'README.md', label: 'README.md' } }));
  await fixture.invoke({ op: 'thread.send', id: 't', text: 'PRESERVE_ON_FAILED_SEND', attachments: [], context: [detail.reference] });
  await expect.poll(async () => (await fixture.snapshot()).data.threads[0].status).toBe('idle');
  await writeFile(join(fixture.project, 'README.md'), 'CHANGED_AFTER_ORIGINAL_SEND');
  await fixture.page.getByRole('button', { name: '重新生成回答', exact: true }).click();
  await fixture.page.getByRole('dialog', { name: '重新生成回答' }).getByRole('button', { name: '创建分支并发送', exact: true }).click();
  await expect(fixture.page.getByText('引用版本已变化，请查看详情并刷新引用', { exact: false })).toBeVisible();
  await expect(fixture.page.getByLabel('向 Pi 发送消息', { exact: true })).toHaveValue('PRESERVE_ON_FAILED_SEND');
  const state = await fixture.snapshot(), branch = state.data.threads.find(t => t.revision?.parentThreadId === 't')!;
  expect(branch.items).toEqual([]);
  expect(state.data.ui.threads[branch.id].contextReferences).toEqual([detail.reference]);
  expect(fixture.calls.length).toBe(1);
  await fixture.restart();
  expect((await fixture.snapshot()).data.ui.threads[branch.id].draft?.text).toBe('PRESERVE_ON_FAILED_SEND');
  await fixture.page.locator('.composer-reference-open').click();
  const dialog = fixture.page.getByRole('dialog', { name: '引用详情', exact: true });
  await dialog.getByRole('button', { name: '刷新引用', exact: true }).click();
  await expect(dialog.getByRole('alert')).toHaveCount(0);
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await fixture.page.getByRole('button', { name: '发送消息', exact: true }).click();
  await expect.poll(() => fixture.calls.length).toBe(2);
  await expect.poll(async () => (await fixture.snapshot()).data.threads.find(t => t.id === branch.id)!.status).toBe('idle');
  expect(JSON.stringify(fixture.calls.at(-1))).toContain('CHANGED_AFTER_ORIGINAL_SEND');
});
