test('search paginates beyond two hundred matches, retains previous pages and opens the selected line', async () => {
  const page = fixture.page;
  const lines = Array.from({ length: 451 }, (_, index) => '分页目标 ' + (index + 1));
  await writeFile(join(fixture.project, 'many.txt'), lines.join('\n'));
  await page.getByLabel('内容', { exact: true }).check();
  await page.getByRole('textbox', { name: '搜索项目文件', exact: true }).fill('分页目标');
  const results = page.getByRole('region', { name: '文件搜索结果' });
  const pagination = results.getByRole('navigation', { name: '搜索结果分页' });
  await expect(results).toHaveAttribute('aria-busy', 'false');
  await expect(results.locator('.file-search-result')).toHaveCount(200);
  await expect(pagination).toContainText('第 1 页');
  await pagination.getByRole('button', { name: '下一页', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(pagination).toContainText('第 2 页');
  await expect(results.locator('.file-search-result').first()).toContainText('many.txt:201');
  await pagination.getByRole('button', { name: '下一页', exact: true }).click();
  await expect(pagination).toContainText('第 3 页');
  await expect(results.locator('.file-search-result')).toHaveCount(51);
  await expect(results.getByRole('status')).toHaveText('找到 451 条结果');
  await expect(pagination.getByRole('button', { name: '下一页', exact: true })).toBeDisabled();
  await pagination.getByRole('button', { name: '上一页', exact: true }).click();
  await expect(results.locator('.file-search-result').first()).toContainText('many.txt:201');
  await results.locator('.file-search-result').first().click();
  const editor = page.getByLabel('文件内容 many.txt', { exact: true });
  await expect(editor).toBeFocused();
  expect(await editor.evaluate(node => (node as HTMLTextAreaElement).selectionStart)).toBe(lines.slice(0, 200).join('\n').length + 1);
  await pagination.getByRole('button', { name: '上一页', exact: true }).click();
  await expect(results.locator('.file-search-result').first()).toContainText('many.txt:1');
  await expect(results.locator('.file-search-result')).toHaveCount(200);
});

