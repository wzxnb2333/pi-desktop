  await page.getByRole('treeitem', { name: 'entry.txt', exact: true }).focus();
  await expect.poll(async () => (await fixture.snapshot()).data.ui.threads.t.fileTreeFocus).toBe('src/entry.txt');
  await fixture.invoke({ op: 'ui.threadPatch', threadId: 't', patch: { draft: { text: '保留草稿', attachments: [] }, folds: { example: true } } });
  const other = await fixture.invoke({ op: 'thread.create', projectId: 'p', worktree: false }) as Thread;
  await page.locator('.thread-main').filter({ hasText: other.title }).click();
  if (!await page.locator('.review-pane').isVisible()) await taskAction(page, '查看变更');
  await page.getByRole('button', { name: '新标签', exact: true }).click();
  await page.locator('.tool-launcher').getByRole('button', { name: '文件', exact: true }).click();
